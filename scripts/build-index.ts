// Regenerates every index from the tool docs' frontmatter. Never edit the outputs by hand:
//   docs/design/README.md            catalogue overview, one row per section
//   docs/design/<section>/README.md  one row per tool in the section
//   docs/design/people.md            design engineers worth following
//   data/index.json                  flat, machine-readable index of every doc
// Usage: bun run index
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { ROOT, loadCatalogue, readDoc } from './lib'

const { tools, people, scraped } = loadCatalogue()
const GENERATED = '<!-- Generated by `bun run index` from doc frontmatter. Do not edit by hand. -->'
const cell = (v: unknown) =>
  String(v ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ')
const list = (v: unknown) => (Array.isArray(v) ? v.join(', ') : '')
const PAYWALL_LABEL: Record<string, string> = { free: 'Free', freemium: 'Freemium', paid: 'Paid', unknown: 'Unknown' }

type Entry = Record<string, unknown> & { section: string; section_slug: string; slug: string; doc: string }
const entries: Entry[] = tools.map((t) => {
  const meta = readDoc(t.doc)?.meta ?? {}
  return {
    ...meta,
    name: t.name,
    slug: t.slug,
    section: t.section,
    section_slug: t.section_slug,
    source_url: t.url,
    designeer_url: t.designeer_url,
    designeer_blurb: t.description,
    paywall: meta.paywall ?? 'unknown',
    doc: t.doc
  }
})

const sections = [...new Map(tools.map((t) => [t.section_slug, t.section])).entries()]
const sectionBlurb = new Map<string, string>()
const blurbs: Record<string, string> = {
  'design-galleries': 'Design galleries, interface patterns, and web inspiration.',
  'component-libraries': 'Production UI primitives and accessible component libraries.',
  development: 'Modern code editors, runtimes, and local tooling.',
  'agents-mcp': 'Coding agents, local MCP servers, and machine specs.',
  motion: 'Animation timing, spring physics, and motion libraries.',
  'interface-design': 'Interface design canvases, tokens, and layout systems.',
  type: 'Curated web typefaces, pairings, and font optimization.',
  color: 'Color palette generators, contrast checkers, and color math.',
  '3d': '3D modeling tools and WebGL rendering engines online.',
  shaders: 'Interactive fragment shaders, procedural noise, and canvas effects.',
  icons: 'Crisp icon families and glyphs for modern interfaces.',
  utilities: 'Developer utilities that accelerate frontend workflows.',
  desktop: 'Native macOS and desktop utility apps for productivity.',
  'video-capture': 'Screen recording software, timeline editors, and demo tools.',
  whiteboard: 'Infinite canvas workspaces for wireframing and systems architecture.',
  deploy: 'Hosting platforms, edge runtimes, and deployment infrastructure.',
  reading: 'Essential books, design engineering essays, and craft tutorials.'
}
for (const [slug] of sections) sectionBlurb.set(slug, blurbs[slug] ?? '')

const count = (xs: Entry[], p: string) => xs.filter((e) => e.paywall === p).length

// Per-section READMEs
for (const [slug, name] of sections) {
  const rows = entries.filter((e) => e.section_slug === slug)
  const md = [
    GENERATED,
    '',
    `# ${name}`,
    '',
    `> ${sectionBlurb.get(slug)}`,
    '',
    `${rows.length} tools — ${count(rows, 'free')} free, ${count(rows, 'freemium')} freemium, ${count(rows, 'paid')} paid, ${count(rows, 'unknown')} unknown. Source: [Designeer](${rows[0].designeer_url}).`,
    '',
    '| Tool | Paywall | Open source | Agent-friendly | Best for | What it is |',
    '| ---- | ------- | ----------- | -------------- | -------- | ---------- |',
    ...rows.map(
      (e) =>
        `| [${cell(e.name)}](./${e.slug}.md) | ${PAYWALL_LABEL[String(e.paywall)] ?? cell(e.paywall)} | ${e.open_source === true ? 'Yes' : e.open_source === false ? 'No' : '—'} | ${e.agent_friendly === true ? 'Yes' : e.agent_friendly === false ? 'No' : '—'} | ${cell(list(e.best_for))} | ${cell(e.designeer_blurb)} |`
    ),
    '',
    '[← All sections](../README.md)',
    ''
  ].join('\n')
  mkdirSync(join(ROOT, 'docs/design', slug), { recursive: true })
  writeFileSync(join(ROOT, 'docs/design', slug, 'README.md'), md)
}

// Catalogue overview
const overview = [
  GENERATED,
  '',
  '# Design catalogue',
  '',
  `${entries.length} tools across ${sections.length} sections, scraped from [Designeer](https://designeer.xyz) on ${scraped} and researched one by one. Each tool has its own doc with source URL, paywall, how to use, examples, and agent notes.`,
  '',
  `**Paywall overview:** ${count(entries, 'free')} free · ${count(entries, 'freemium')} freemium · ${count(entries, 'paid')} paid · ${count(entries, 'unknown')} unknown.`,
  '',
  '| Section | Tools | Free | Freemium | Paid | What it covers |',
  '| ------- | ----- | ---- | -------- | ---- | -------------- |',
  ...sections.map(([slug, name]) => {
    const rows = entries.filter((e) => e.section_slug === slug)
    return `| [${name}](./${slug}/README.md) | ${rows.length} | ${count(rows, 'free')} | ${count(rows, 'freemium')} | ${count(rows, 'paid')} | ${sectionBlurb.get(slug)} |`
  }),
  '',
  `Also: [People worth following](./people.md) — ${people.length} design engineers.`,
  '',
  'Machine-readable: [`data/index.json`](../../data/index.json) (every doc’s frontmatter) and [`data/catalogue.json`](../../data/catalogue.json) (raw scrape).',
  ''
].join('\n')
writeFileSync(join(ROOT, 'docs/design/README.md'), overview)

// People
const peopleMd = [
  GENERATED,
  '',
  '# People worth following',
  '',
  `${people.length} design engineers and creators recommended by [Designeer](https://designeer.xyz/designers), scraped ${scraped}. Read their sites for craft references, component ideas, and interaction details.`,
  '',
  '| Name | Known for | Site | Social |',
  '| ---- | --------- | ---- | ------ |',
  ...people.map(
    (p) =>
      `| ${cell(p.name)} | ${cell(p.description)} | [${cell(new URL(p.url).host.replace(/^www\./, ''))}](${p.url}) | ${p.sameAs.map((s) => `[${cell(new URL(s).host.replace(/^www\./, ''))}](${s})`).join(' ')} |`
  ),
  '',
  '[← All sections](./README.md)',
  ''
].join('\n')
writeFileSync(join(ROOT, 'docs/design/people.md'), peopleMd)

writeFileSync(join(ROOT, 'data/index.json'), JSON.stringify({ generated_from: 'docs/design/**/*.md frontmatter', tools: entries }, null, 1) + '\n')
console.log(`indexed ${entries.length} tools, ${sections.length} sections, ${people.length} people`)
